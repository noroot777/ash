// 执行者**新开 CLI 会话**的首条消息里那两条产出质量规则。
//
// 用户 2026-10-30 拍板:把那两句**原句**加进开场提示词,不加判据、不加护栏、不加判断表,
// 也不做修复交接契约之类的展开(那套方案已被明确否决)。所以这个文件只有两样东西 ——
// 原句本体,和「这一轮该不该贴」那个判据。想往里加字的人先看一眼
// `server/scripts/test-prompt-budget.ts`:加字必须在 diff 里改掉一个数,改不动就加不进来。
//
// 为什么零依赖、单独一个文件而不住在 `run-prompts.ts`:四个拼装入口里有一个在
// `server/src/team/` 下,而 `run-prompts.ts` → `settle-status.ts` → `team/inbox.ts` →
// `team/prompts.ts` 本来就是一条现成的链 —— 规则本体放进 `run-prompts.ts` 就成了环。
// (ESM 下只有在模块求值期取值才真炸,但没必要给下一个人留这个雷。)

/**
 * 原句,一字不改。
 *
 * 末尾那个空行是**接口的一部分**:四个拼装器都把它当成一个独立段落直接拼在前后两段之间,
 * 靠它和相邻段落隔开(同 `AUTONOMY` 的分寸)。
 */
export const CRAFT_RULES =
  "避免不必要的次级标签和描述，让布局本身解释界面\n" +
  "结合第一性原理和成熟实践，从根因修复 Bug，避免只遮住表面症状\n\n";

/** 「这一轮算不算执行者的新会话首条消息」。两条判据缺一不可,各自为什么见字段注释。 */
export interface CraftContext {
  /**
   * 模型手上**有没有旧上下文**。
   *
   * 判据刻意落在这件事上,而不是「走的哪个 API 入口」:`runTask` 从来不是「所有新会话」的
   * 同义词,按入口接必然漏掉另外几类真正的首条消息 —— 首次 @ 另一位执行者进来、旧会话
   * 接不上或被 `/clear` 清掉之后新开的那一条、团队调度台开台、以及「先规划后实施」里
   * 开场就是规划回合的那一条。
   *
   * 各处都已经有同源的现成判据(`resuming`):浏览器策略发全文还是缩略版就是按它分的。
   * 这里挂的是同一个判据,不是另发明一个。
   */
  freshContext: boolean;
  /**
   * 这一轮交的是**结论**而不是新一版代码:历史独立审查任务、就地验证轮、自由工作流的
   * 审查回合。规则讲的是怎么写代码和界面,对只写报告的那一轮讲它纯属按轮次付费。
   */
  verifying: boolean;
}

/**
 * 这一轮该贴的那一段;不该贴就是空串。
 *
 * **四个拼装入口一律只认这个函数的产物**:槽位收的是 `CraftContext` 而不是渲染好的字符串,
 * 于是没有任何入口能自己造一段(或者图省事传个空串)—— 想绕过判据就得改这个函数,而它被
 * 体积闸的判据断言和 `PLACEMENT` 单源表两头夹着。
 */
export function craftRulesFor(ctx: CraftContext): string {
  return ctx.freshContext && !ctx.verifying ? CRAFT_RULES : "";
}
