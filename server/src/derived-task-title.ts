// 派生任务（审查意见转出、合并结果修复…）的标题拼法，一处定义。
//
// 顺序是**先原任务名、后派生缘由**，不是反过来。缘由放前面时，列表里连着几条派生任务
// 只剩同一串前缀（「承接第 1 轮审查的越界意见：…」「修复合并结果：…」），真正区分它们
// 的那半截被挤到省略号之后，用户只能逐条点开才知道是哪个任务（用户 2026-09-30 反馈）。
// 派生任务的来源在详情页另有一行「来自任务 · X」，缘由本身也不是列表里要一眼扫的东西。
//
// 原任务名截断、缘由不截：缘由是固定短语，截了就认不出这是哪一类派生；原任务名长短
// 不受控，整段拼上去只会把缘由挤出可视区。

/** 标题里给原任务名留的长度：够一眼认出是哪个任务，又不至于把缘由挤没。 */
const SOURCE_LEN = 40;

export function derivedTaskTitle(sourceTitle: string, reason: string): string {
  const name = sourceTitle.trim() || "(无标题任务)";
  return `${name.length > SOURCE_LEN ? `${name.slice(0, SOURCE_LEN)}…` : name} · ${reason}`;
}
