/**
 * 「这次启动的管理责任已经交给用户了」——「签过字的进程一个都不碰」那条承诺的**唯一判据**。
 *
 * 为什么单独一个模块:这个判断散在击杀层、关服收人、闲置回收、容量账里各写一遍
 * `session.abandoned != null`,而它们问的是同一件事。放在同一个名字下面,新增一条破坏性
 * 动作时「要不要先问这一句」是看得见的。
 *
 * 承诺怎么兑现分两档,缺一不可:
 *
 *   ① **串行化**(terminal-management-lock.ts):交接自己要先拿到这条命令 + 这条会话的锁,
 *      所以它**等**在途那趟停止/重启/删除走完才落。于是「签字成功返回」这句话的含义是
 *      确定的 —— 那一刻没有任何破坏性动作还在半路上。早先交接只是往内存里写一格,实测签字
 *      返回 200、服务当时还活着,几秒后被先前那趟停止的 KILL 收掉,界面上还写着「已放弃
 *      管理」(第 1 轮自由审查 191hQL5abga7 必须修 1)。
 *   ② **兜底**:信号出口(`signalSessionTree`)、关服端口收人、闲置回收、destroy 各自入口
 *      再问一遍这一句。锁已经保证排队,这一档防的是**以后**新接一条没走锁的路。
 *
 * 为什么不是「撤销在途那趟的杀进程权限」:用户点过停止,停止就该跑完它自己那一趟 ——
 * 签字接手说的是「剩下的归我」,不是「取消我刚点的停止」。半路撤销会留下一个半死的服务,
 * 而签字快照里还列着那些刚被杀掉的号。排队虽然要多等几秒(停止脚本有自己的超时上限,
 * 等得到头),但「用户签字时看到的就是真实现场」这件事保住了。
 */
export function handedOver(launch: { abandoned?: unknown } | null | undefined): boolean {
  return launch?.abandoned != null;
}
