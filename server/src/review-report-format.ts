/**
 * 断线续跑那一回合发的缩略版。
 *
 * 它跟完整版是**同一张表的两个渲染**，所以不存在「这一条要不要也写进提醒」的取舍——
 * 写规则的时候两种说法一起写，拼接负责让两边都有。写成四栏嵌套而不是平铺分号，纯粹
 * 为了密度：规则全在，还要塞进整条续跑消息的长度闸（`test-review-resume.ts` 钉着上限，
 * 量的是非规则的那部分——这句话的全部意义是「别从头重发任务书」）。
 */
