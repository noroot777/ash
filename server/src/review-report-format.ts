// 审查报告开头那一节的格式。独立成文件是因为**两条审查路径共用**：就地验证轮
// （`review-prompts.ts`）和自由工作流审查（`free-review-prompts.ts`）。只写在其中一边，
// 另一边产出的报告就还是老样子——ascut 那批被抽查的报告全出自自由工作流那条。
//
// 这不只是措辞讲究，它是**跟前端的契约**：`web/src/components/reviewReportSections.ts`
// 认「第一个二级标题在讲结论」来拆分，摘要段铺开给人看，其余收进「展开技术明细」。
// 对不上就整篇铺开（存量报告如此），内容一个字不会少——盘上的 report.md 始终是完整的，
// 修复 agent 读的就是它，所以界面上才敢折叠。
//
// ## 为什么是一张表，而不是两段文案
//
// 这份契约有**两个渲染**：派审时发完整版（`REPORT_SUMMARY_FORMAT`，讲透、带判据），
// 断线续跑时只发缩略版（`REPORT_SUMMARY_REMINDER`，挤成一句——那一轮不重发任务书，
// 格式要求只有它跟得到底）。
//
// 两份文案分开手写时，往完整版加一条规则不会自动出现在缩略版里。2026-09-26 连续四轮
// 审查都在报同一件事（「提醒里又漏了 N 条」）：每轮补两三条，下一轮再被找出剩下的。
// 第三轮加了一张测试侧的核对清单，第四轮的发现是那张清单**自己**漏登记了排序规则
// ——第三份要人工同步的副本而已。
//
// 所以现在**只有一份源**：下面这张 `SUMMARY_RULES`，每条规则同时写出两种说法，两个
// 常量都从它拼出来。加规则时 `short` 是必填字段，漏了编译不过；这是「让它编译不过」
// 那一档，不是靠自觉，也不靠任何一张需要同步的清单。
//
// 规则的出处（2026-09-26 抽查 ascut 的真实报告）：
// ① 现象在前、机制在后 —— `zs6JLcw1VAdr` 第 10 轮的标题「存储短暂失败后恢复可写，会丢弃
//    唯一的跨项目悬账并在旧字幕上放行烧录」，信息全在，但前 26 个字是机制，读到句尾才
//    碰到「跟我有什么关系」。
// ② 术语禁令要管到自造名词 —— 上面那句里的「悬账」「写后快照」都不是代码标识符，
//    只禁文件名/函数名一个都拦不住。
// ③ 严重度只留两档 —— `LqhF7g_rqANy` 第 1 轮用了「建议修 / 程度轻 / 程度中 /
//    程度中·偏取舍 / 不构成缺陷」五种说法，读者无法据此决定收不收。
// ④ 禁止嵌套条目 —— 同一份报告的「缺陷 6」藏在「缺陷 1」正文里，扫标题永远找不到。
// ⑤ 首句点名最要命的那条 + 按严重程度排 + 摘要最多 5 条 —— `LqhF7g_rqANy` 第 1 轮
//    11 个条目平铺，全文没有一句回答「哪一条最要命」。数字（「有 11 条」）回答不了这个
//    问题，所以首句必须点名；顺序也得按用户会踩到的程度排，否则前 5 条展开的可能恰好
//    是最轻的那几条。**分流不是截断**：完整三行照写，写在明细里，一条不丢。

export type SummaryRule = {
  /** 出问题时报给人看的名字，也是回归测试里的标识。 */
  id: string;
  /** 完整版里的说法：讲透、带判据、带例子。**自带前后分隔符**，拼接时不再补。 */
  full: string;
  /** 缩略版里的说法：挤成一句。同样自带分隔符。必填——漏了编译不过。 */
  short: string;
  /**
   * 两种说法都必须命中的关键词。只给**枚举型**规则用：一句话里列了五样东西，改写时
   * 掉一样是无声的，拼接管不住（第 4 轮审查前，缩略版就这么丢过 `git status` 和
   * 浏览器通道降级说明）。其余规则靠拼接本身保证在场，不需要探针。
   */
  probes?: RegExp[];
};

