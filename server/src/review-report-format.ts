// 审查报告开头那一节的格式。独立成文件是因为**两条审查路径共用**：就地验证轮
// （`review-prompts.ts`）和自由工作流审查（`free-review-prompts.ts`）。只写在其中一边，
// 另一边产出的报告就还是老样子——ascut 那批被抽查的报告全出自自由工作流那条。
//
// 这不只是措辞讲究，它是**跟前端的契约**：`web/src/components/reviewReportSections.ts`
// 认「第一个二级标题在讲结论」来拆分，摘要段铺开给人看，其余收进「展开技术明细」。
// 对不上就整篇铺开（存量报告如此），内容一个字不会少——盘上的 report.md 始终是完整的，
// 修复 agent 读的就是它，所以界面上才敢折叠。
//
// 五条子规则各有出处（2026-09-26 抽查 ascut 的真实报告）：
// ① 现象在前、机制在后 —— `zs6JLcw1VAdr` 第 10 轮的标题「存储短暂失败后恢复可写，会丢弃
//    唯一的跨项目悬账并在旧字幕上放行烧录」，信息全在，但前 26 个字是机制，读到句尾才
//    碰到「跟我有什么关系」。
// ② 术语禁令要管到自造名词 —— 上面那句里的「悬账」「写后快照」都不是代码标识符，
//    只禁文件名/函数名一个都拦不住。
// ③ 严重度只留两档 —— `LqhF7g_rqANy` 第 1 轮用了「建议修 / 程度轻 / 程度中 /
//    程度中·偏取舍 / 不构成缺陷」五种说法，读者无法据此决定收不收。
// ④ 禁止嵌套条目 —— 同一份报告的「缺陷 6」藏在「缺陷 1」正文里，扫标题永远找不到。
// ⑤ 首句点名最要命的那条 + 摘要最多 5 条 —— `LqhF7g_rqANy` 第 1 轮 11 个条目平铺，
//    全文没有一句回答「哪一条最要命」。数字（「有 11 条」）回答不了这个问题，所以首句
//    必须点名；而 11 条全铺在摘要里又正是用户看不下去的样子，所以摘要展开前 5 条、
//    其余只列标题并指向明细。**分流不是截断**：完整三行照写，写在明细里，一条不丢。

export const REPORT_SUMMARY_FORMAT =
  `报告开头必须先写一节 \`## 结论\`（就用这四个字起头，前端靠它把摘要和明细分开），` +
  `四个小标题固定，写完再写技术明细：\n\n` +
  `**能不能验收**：一句话。不能的话写「不能 —— 有 N 条必须先修，最要命的是<一句话点名那一条>」。` +
  `只写「有 N 条」不算数：用户要的是「最严重的是什么」，数字回答不了这个问题。\n\n` +
  `**现在什么能用了**：用户在界面上能看见的行为。没做成就写「没有新增可用的东西」。\n\n` +
  `**必须修的问题**：每条一个小标题，固定三行；不许把一条塞进另一条的正文里，` +
  `扫标题要能数清楚一共几条：\n` +
  `- 第一行「你会遇到」：用户会看到什么错的结果。这一行里不许出现任何机制——` +
  `不只是文件名、函数名、变量名，也包括你为了讲清楚而自己起的名词。` +
  `判据：没读过这份代码的人能不能照着复现。\n` +
  `- 第二行「为什么」：一句话讲机制，这里才允许用术语。\n` +
  `- 第三行「建议怎么修」：一句话。\n` +
  `没有问题时，这一栏只写「没有发现问题」六个字，不许拿核对记录填——` +
  `「我检查了 X 没问题」属于下面的明细，放在这里会被当成问题清单读。\n` +
  `按用户会踩到的严重程度排序，**摘要里最多展开 5 条**。还有更多时，在第 5 条后面用一行写` +
  `「其余 N 条：<标题>、<标题>……完整写在下面的技术明细里」，并把它们的完整三行原样写进明细。` +
  `一条都不许丢，但也别把十几条全铺在摘要里——那正是用户看不下去的样子。\n\n` +
  `**不拦验收、但你该知道的**：一行一条，不写原因。\n\n` +
  `严重度只有「拦验收」和「不拦」两档，靠上面两个小标题区分；不要再写「程度轻/中/偏取舍」` +
  `这类第二套刻度，要细分写进下面的明细。\n\n` +
  `这一节里不许出现基线 hash、git status、清场记录、命令输出、浏览器通道降级说明——` +
  `它们照写，写在下面的明细里。\n\n`;

/**
 * 每回合提醒里的一句话版。被打断续跑时，格式要求只有它跟得到底——**所以它必须带全
 * `FORMAT` 里的每一条规则**，一条都不能少。
 *
 * 判据：这条规则丢了，报告会不会退回改动之前的样子？会就得写进来。而答案几乎总是
 * 「会」——所以这里不做取舍，`FORMAT` 有几条这里就有几条，留在那边的只有讲解和判据
 * （「判据：没读过这份代码的人能不能照着复现」之类），规则本体一条不少。
 *
 * **这不是靠自觉。**`server/scripts/review-summary-rules.ts` 把契约拆成一张规则表，
 * `test-review-flow.ts` / `test-review-resume.ts` 拿它逐条比对完整版和缩略版。往
 * `FORMAT` 加规则而忘了加进这里，当场红并报出漏了哪几条——这一段曾经连续三轮被审查
 * 点名「又漏了 N 条」，靠人记是记不住的。
 *
 * 写法是四栏嵌套而不是平铺分号，纯粹为了密度：规则全在，还要塞进整条续跑消息的长度
 * 闸里（`test-review-resume.ts` 钉着上限）。这句话的全部意义是「别从头重发任务书」。
 */
