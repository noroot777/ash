/** 派审回合发的完整版。 */
export const REVIEW_SWEEP_PROTOCOL = "【一次查全（这一轮的扫描义务）】\n"
  + SWEEP_RULES.map((rule) => rule.full).join("");

/**
 * 交回执行者时必须补的一句：**报告说「这是类问题」的那几条，按它指的层级修**。
 *
 * 不补这一句，上面那条「报类不报个例」就会被修复提示自己吃掉：修复提示的开场白是
 * 「按报告修复，**不要扩大原任务边界**」，而「别在这一层打补丁，去 X 层加不变量」恰好
 * 长得像扩大边界。执行者两句话打架时只能自己挑一个，挑错了没人会发现（两边看着都
 * 「按报告改了」）—— 于是审查者好不容易报出来的类，又被改回成一个触发组合的补丁，
 * 下一轮再崩出同类的第 N+1 个。
 *
 * 反向的门没有开：报告**没有**写成类问题的，仍然照原样修，这一句不是「随便重构」的许可。
 *
 * 但「怎么修」不等于「该不该在这里修」：**边界由任务目标定，不由报告给的那个标签定**。
 * 这一句最初写成了无条件的「报告点名的根因层级属于本任务边界之内」，于是整条意见——
 * 哪怕根因和全部实例都落在与任务无关的管线里——也被判成界内。判据本体现在只有一份，
 * 在 `@ash/shared/free-workflow` 的 `CLASS_PROBLEM_BOUNDARY`（三种处置、不写具体出口；
 * 这段话被预设/旧验证那条线共用，那边没有 `dispute_review`）。
 */
export const CLASS_REPAIR_NOTE =
  "报告里写明「这是类问题」的那几条，按它指出的层级修根因。报告没写成类问题的，照原样修。"
  + CLASS_PROBLEM_BOUNDARY + "\n";

/** 续跑那一回合发的缩略版：只保留收尾时仍然做得到的那几条（`short` 非 null）。 */
export const REVIEW_SWEEP_REMINDER = SWEEP_RULES
  .map((rule) => rule.short)
  .filter((text): text is string => !!text)
  .join("");
