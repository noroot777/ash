// 「一次查全」协议：审查者在**一轮之内**该把问题找到什么程度。
//
// 为什么需要它 —— 2026-10-13 在 data/runs 全库 1378 份真实报告上数出来的三件事：
// ① 275 份用新摘要格式写的报告里，145 份（53%）整份只报了 1 条阻塞问题，224 份（81%）≤2 条。
// ② 把报告按审查链拼起来：38 条跑到 3 轮以上的链，第 1 轮合计报出 99 条，整条链累计报出
//    349 条 —— **首轮召回率 28%**。后面那 72% 不全是「上一轮修出来的新问题」（用户 2026-10-13
//    的原话，数据也对得上），相当一部分第 1 轮就在那儿，只是没被报出来。
// ③ 最贵的形态是**同一个类的实例被一轮一报**：`MiBg8G40scWo/LZxc8Pm_akLy` 10 轮 10 条，全是
//    「AI 填写的结果归属判据不可靠」的不同触发组合（多开页 / 复制标签 / 刷新 / 局域网 / 原页
//    卡顿 / 刷新后又手改）；`zs6JLcw1VAdr/IsecnyJQER8z` 10 轮 10 条，全是「客户端拿本地状态
//    推断写有没有落盘」的不同失败组合（pagehide / 租约到期 / 清 localStorage / 写失败 / 写
//    超时 / 切项目 / 恢复可写）。每轮只报自己复现到的那一条触发路径，执行者就只修那一条，
//    下一轮换一个组合再来 —— 链没有终点。而第 10 轮那份报告自己在最后一段写出了正确的层级
//    （「后端单调版本 + 烧录时校验」），也就是说审查者**看得见**类，只是没被要求报类。
//
// 三件事都不是「审查者不够聪明」，是**提示词只要求它找出缺陷、没要求它扫完**：结论字段是
// 二值的（verified / verify_failed），第一条阻塞缺陷一落地，这一轮的义务就履行完了；而单条
// 发现的证据成本极高（上面那 10 轮里，单条带 6 步复现脚本、状态 JSON、两张截图加 SHA-256
// 校验），深度一开就把预算吃光。所以这份协议只做两件事：把**停机条件**从「够判不通过了」
// 改成「该扫的面扫完了」，把**证据预算**按严重度分级，让剩下的面扫得起。
//
// 形状照 `review-report-format.ts` 那张表，理由一样：派审发完整版、续跑发缩略版，两份文案
// 分开手写时，往完整版加一条不会自动出现在缩略版里（那份文件记着连续四轮审查都在报「提醒
// 里又漏了 N 条」）。所以这里也只有一份源。
//
// 跟那张表的**唯一差别**：这里的 `short` 允许显式为 null。续跑那一回合是「从中断处接着做」，
// 它的广度扫描已经过去了，再对它说一遍「先广后深」只会让它从头重扫 —— 那正是续跑路径省下来
// 的 10M token。所以「只在开工时有意义」的规则写 null，**但必须写出来**：可选字段会让新加的
// 规则默认不进提醒，那正是上面那份文件栽过两次的坑。

import { CLASS_PROBLEM_BOUNDARY, REGRESSION_POLICY } from "@ash/shared/free-workflow";

export type SweepRule = {
  /** 出问题时报给人看的名字，也是回归测试里的标识。 */
  id: string;
  /** 派审回合发的说法：讲透、带判据、带实测代价。**自带前后分隔符**。 */
  full: string;
  /**
   * 续跑提醒里的说法，同样自带分隔符；`null` = 这条只在开工时有意义，续跑不重发。
   * 必填（写 `null` 也算写），理由见文件头最后一段。
   */
  short: string | null;
  /** 两种说法都必须命中的关键词；`short` 为 null 时只核 `full`。 */
  probes: RegExp[];
};

/** 必须字字一致的硬限定：放行一处，报告就退回「只报我复现到的那一条」。 */
