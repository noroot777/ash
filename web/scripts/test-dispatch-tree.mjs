import assert from "node:assert/strict";
import { buildDispatchForest, forestRoot, forestLatest, keepForestVisible } from "../src/workspace/dispatchForest.ts";
import { dispatchFacts, dispatchTally, dispatchTallySaid, dispatchSubtree } from "../src/lib/dispatchTree.ts";
import { dispatchPath, dispatchFamily, dispatchLevel, dispatchBranchAccepted, dispatchLook, dispatchMatchesFilter } from "../src/lib/dispatchFamily.ts";
import { spreadCounts, spreadVisibleTasks } from "../src/workspace/useSidebarSpread.ts";
import { sidebarSelectionId, stepTaskId } from "../src/workspace/sidebarNavigation.ts";
import { scopeTasks } from "../src/workspace/taskScope.ts";
import { readDispatchFolds, writeDispatchFolds, revealDispatchSelection } from "../src/task-detail/dispatched/dispatchFolds.ts";
import { dispatchedMeta, dispatchedOrder, dispatchedWord } from "../src/task-detail/dispatched/dispatchedRows.ts";
import { readState, applyTabPolicy } from "../src/inspector/inspectorState.ts";
import { rememberFamilyInspector, takeInspectorEntry } from "../src/task-detail/dispatched/inspectorNavigation.ts";
import { taskParentLink, taskParentRelation } from "../src/lib/taskParent.ts";
import { startDispatchArrivals, observeDispatchArrivals } from "../src/task-detail/dispatched/dispatchArrivals.ts";

const now = Date.parse("2026-11-16T12:00:00Z");
const task = (id, extra = {}) => ({
  id, projectId: "p1", parentId: null, groupId: null, mode: "single", title: id, status: "done", stage: "accepted",
  createdAt: new Date(now - 48 * 3600_000).toISOString(), updatedAt: new Date(now - 48 * 3600_000).toISOString(), ...extra,
});
const ids = (rows) => rows.map((item) => item.id);
const root = task("root");
const mid = task("mid", { dispatchedBy: "root", pinnedAt: 1 });
const leaf = task("leaf", { dispatchedBy: "mid", status: "paused", stage: null, question: "选哪个？", updatedAt: new Date(now).toISOString() });
const run = task("run", { dispatchedBy: "root", status: "running", stage: null });
const worker = task("worker", { parentId: "team", dispatchedBy: "root" });
const all = [root, mid, leaf, run, worker];
const forest = buildDispatchForest(all);
assert.deepEqual([...forest.nested].sort(), ["leaf", "mid", "run"]);
assert.equal(forestRoot(forest, "leaf"), "root");
assert.equal(forestLatest(forest, root), leaf.updatedAt);
assert.equal(keepForestVisible(forest, () => false, 24 * 3600_000, () => now)(root), true);
assert.equal(sidebarSelectionId(["before", "root", "after"], "leaf", all), "root");
assert.equal(stepTaskId(["before", "root", "after"], sidebarSelectionId(["before", "root", "after"], "leaf", all), 1), "after");
assert.equal(buildDispatchForest([leaf], all).nested.size, 0);
assert.equal(buildDispatchForest([root, leaf], all).host.get("leaf"), "root");
assert.equal(buildDispatchForest([mid, leaf], all).host.get("leaf"), "mid");
const cycle = buildDispatchForest([task("a", { dispatchedBy: "b" }), task("b", { dispatchedBy: "a" })]);
assert.equal(cycle.nested.size, 1);
assert.deepEqual(ids(dispatchPath(leaf, all)), ["root", "mid", "leaf"]);
assert.equal(taskParentRelation(taskParentLink(leaf, all)), "父任务");
assert.equal(taskParentRelation(taskParentLink({ ...leaf, originTaskId: "mid", creationOrigin: { kind: "system" } }, all)), "来自任务");
assert.equal(taskParentRelation(taskParentLink(worker, all)), "所属团队");
for (const item of [root, mid, leaf]) assert.equal(dispatchFamily(item, all).root.id, "root");
const bridged = [root, { ...mid, archived: true }, leaf];
assert.deepEqual(ids(dispatchFamily(root, bridged).children.get("root")), ["leaf"]);
assert.equal(dispatchFacts(bridged).count("root"), 0);
assert.equal(dispatchFacts(bridged).needsYou("root"), true);
assert.deepEqual(dispatchTally(dispatchFacts(all), "root"), { count: 2, warn: true });
assert.equal(dispatchTallySaid({ count: 2, warn: true }), "2 个子任务，有要你处理的");
assert.equal(dispatchLook(root, all).mark, "wait");
assert.equal(dispatchLook(root, all).phrase.word, "等你答复");
assert.equal(dispatchLook(root, all).phrase.tip, "子任务「leaf」等你答复");
assert.equal(dispatchedWord(root, dispatchLook(root, all)).word, "等你答复");
assert.equal(dispatchLook(root, [root, { ...leaf, dispatchedBy: "root", question: null, status: "failed" }]).mark, "bad");
assert.ok(dispatchMatchesFilter(root, "todo", all));
assert.ok(dispatchMatchesFilter(root, "run", all));
assert.ok(!dispatchMatchesFilter(root, "run", [root, { ...run, archived: true }]));
const scope = { kind: "project", projectId: "p1" };
for (const filter of ["all", "run", "todo"]) assert.deepEqual(ids(spreadVisibleTasks(all, scope, filter)), ["root"]);
assert.equal(spreadCounts(all, scope).all, 1);
assert.equal(spreadCounts(all, scope).todo, 1);
assert.equal(spreadCounts(all, scope).run, 1);
assert.ok(scopeTasks(all, { kind: "tasks" }).some((item) => item.id === "root"));
assert.deepEqual(ids(spreadVisibleTasks([root, { ...mid, projectId: "p2" }, leaf], scope, "todo")), ["root"]);
assert.deepEqual(ids(spreadVisibleTasks([{ ...root, projectId: "p2" }, { ...mid, projectId: "p2" }, leaf], scope, "todo")), ["leaf"]);

let arrivals = startDispatchArrivals("root", [root], now);
for (const snapshot of [[root, mid], all, [root], all]) {
  arrivals = observeDispatchArrivals(arrivals, snapshot);
  assert.equal(arrivals.revision, 0, "初始分批加载和重连追平的历史任务不算新派出");
}
const newlyCreated = (id, extra = {}) => task(id, { dispatchedBy: "root", createdAt: new Date(now + 1).toISOString(), ...extra });
const archivedNew = newlyCreated("archived-new", { archived: true });
arrivals = observeDispatchArrivals(arrivals, [...all, archivedNew]);
arrivals = observeDispatchArrivals(arrivals, [...all, { ...archivedNew, archived: false }]);
arrivals = observeDispatchArrivals(arrivals, all);
arrivals = observeDispatchArrivals(arrivals, [...all, { ...archivedNew, archived: false }]);
assert.equal(arrivals.revision, 0, "已观察的归档项取消归档、消失再回填都不触发");
const lateOldArchived = task("late-old-archived", { dispatchedBy: "root", archived: true });
arrivals = observeDispatchArrivals(arrivals, [...all, lateOldArchived]);
arrivals = observeDispatchArrivals(arrivals, [...all, { ...lateOldArchived, archived: false }]);
assert.equal(arrivals.revision, 0);
const ignored = [newlyCreated("other-parent", { dispatchedBy: "elsewhere" }), newlyCreated("grandchild", { dispatchedBy: "mid" }), newlyCreated("team-worker", { parentId: "team" }), newlyCreated("invalid-time", { createdAt: "invalid" }), newlyCreated("at-entry", { createdAt: new Date(now).toISOString() })];
arrivals = observeDispatchArrivals(arrivals, [...all, ...ignored]);
arrivals = observeDispatchArrivals(arrivals, [...all, { ...ignored[0], dispatchedBy: "root" }]);
assert.equal(arrivals.revision, 0, "别处派出、孙任务、团队执行者、无效时间或关系回填不抢当前任务");
const freshBatch = [newlyCreated("fresh-1"), newlyCreated("fresh-2")];
arrivals = observeDispatchArrivals(arrivals, [...all, ...freshBatch]);
assert.equal(arrivals.revision, 1, "进入后真实新建的一批只触发一次");
const afterBatch = arrivals;
arrivals = observeDispatchArrivals(arrivals, [...all, ...freshBatch.map((item) => ({ ...item, status: "paused" }))]);
assert.equal(arrivals, afterBatch, "状态变化不算新派出");
arrivals = observeDispatchArrivals(arrivals, all);
arrivals = observeDispatchArrivals(arrivals, [...all, ...freshBatch]);
assert.equal(arrivals.revision, 1, "新批次的重复快照不重放");
arrivals = observeDispatchArrivals(arrivals, [...all, task("old-catch-up", { dispatchedBy: "root" }), newlyCreated("fresh-after-reconnect")]);
assert.equal(arrivals.revision, 2, "重连混合快照只识别进入后真正创建的任务");
const reentered = observeDispatchArrivals(startDispatchArrivals("root", [root], now + 100), [...all, ...freshBatch]);
assert.equal(reentered.revision, 0, "刷新或离开后返回，不把此前创建的子任务当成新批次");
assert.equal(startDispatchArrivals("root", [...all, ...freshBatch], now).revision, 0, "首次已有的完整列表只是基准");

const accepted = task("accepted", { dispatchedBy: "root" });
const acceptedChild = task("accepted-child", { dispatchedBy: "accepted" });
const canceled = task("canceled", { dispatchedBy: "root", status: "canceled" });
const family = dispatchFamily(root, [root, mid, leaf, accepted, acceptedChild, canceled]);
const top = dispatchLevel(family.children, "root", "root");
assert.deepEqual(ids(top.accepted), ["accepted"]);
assert.deepEqual(ids(top.rest), ["mid", "canceled"]);
assert.equal(top.acceptedOpen, false);
assert.equal(dispatchLevel(family.children, "root", "accepted-child").acceptedOpen, true);
assert.equal(dispatchLevel(family.children, "accepted", "root").acceptedOpen, true);
assert.equal(dispatchLevel(family.children, "mid", "root").branchOpen, true);
assert.equal(dispatchBranchAccepted(mid, family.children), false);
assert.equal(dispatchBranchAccepted(canceled, family.children), false);
assert.equal(dispatchBranchAccepted({ ...accepted, status: "running" }, family.children), false);

const memory = new Map();
const storage = { getItem: (key) => memory.get(key) ?? null, setItem: (key, value) => memory.set(key, value), removeItem: (key) => memory.delete(key) };
globalThis.window = { localStorage: storage };
globalThis.localStorage = storage;
globalThis.sessionStorage = storage;
writeDispatchFolds("root", new Map([["mid", false], ["accepted:root", false]]));
const manualFolds = readDispatchFolds("root");
const savedFolds = memory.get("ash:subtasks:folds:root");
assert.equal(manualFolds.get("mid"), false);
assert.equal(revealDispatchSelection(manualFolds, family.children, "leaf").get("mid"), true);
const revealedAccepted = revealDispatchSelection(manualFolds, family.children, "accepted-child");
assert.equal(revealedAccepted.get("accepted:root"), true);
assert.equal(revealedAccepted.get("accepted"), true);
assert.equal(revealedAccepted.get("accepted:accepted"), true);
assert.equal(memory.get("ash:subtasks:folds:root"), savedFolds);
const returnedFolds = revealDispatchSelection(readDispatchFolds("root"), family.children, "root");
assert.equal(returnedFolds.get("mid"), false);
assert.equal(returnedFolds.get("accepted:root"), false);
assert.equal(returnedFolds.has("accepted"), false);
writeDispatchFolds("root", new Map([["accepted:root", true]]));
assert.equal(readDispatchFolds("root").get("accepted:root"), true);

const descriptors = ["info", "dispatched", "review", "files", "side-chat", "memos"].map((id) => ({ id, defaultOpen: true }));
const policy = { stateKey: "running", requiredTabId: "info", defaultOpenTabIds: ["info"], defaultActiveTabId: "info", preserveActiveTabIds: ["side-chat", "memos"], focusOnEntry: "dispatched", focusRequest: { key: "batch-1", tabId: "dispatched" } };
const hidden = { openTabs: ["info", "review"], activeTab: "review", visible: false, width: 350, policyKey: "running", focusKey: "batch-1", dismissed: ["dispatched"] };
memory.set("test", JSON.stringify(hidden));
const entry = readState("test", descriptors, false, policy);
assert.equal(entry.visible, true);
assert.equal(entry.activeTab, "dispatched");
assert.ok(entry.openTabs.includes("dispatched"));
assert.ok(!entry.dismissed.includes("dispatched"));
for (const [stateKey, defaultActiveTabId] of [["paused", "info"], ["done", "info"], ["verifying", "review"], ["awaiting_acceptance", "review"]]) {
  const changed = applyTabPolicy(hidden, { ...policy, stateKey, defaultActiveTabId }, descriptors);
  assert.equal(changed.visible, false, "仅状态变化不强行打开面板");
  assert.equal(changed.activeTab, defaultActiveTabId);
  assert.ok(changed.dismissed.includes("dispatched"));
  assert.ok(!changed.openTabs.includes("dispatched"));
}
const newBatch = { ...policy, focusRequest: { key: "batch-2", tabId: "dispatched" } };
const arrived = applyTabPolicy(hidden, newBatch, descriptors);
assert.equal(arrived.activeTab, "dispatched");
assert.equal(arrived.visible, true);
assert.ok(!arrived.dismissed.includes("dispatched"));
const afterArrival = applyTabPolicy({ ...arrived, activeTab: "files", visible: false }, { ...newBatch, stateKey: "paused" }, descriptors);
assert.equal(afterArrival.visible, false);
assert.equal(afterArrival.activeTab, "info");
for (const activeTab of ["side-chat", "memos"]) {
  const preserved = applyTabPolicy({ ...hidden, openTabs: [activeTab], activeTab }, newBatch, descriptors);
  assert.equal(preserved.activeTab, activeTab);
  assert.equal(preserved.visible, false);
}
const kept = readState("test", descriptors, false, { ...policy, entryTab: { id: "files", visible: false } });
assert.equal(kept.activeTab, "files");
assert.equal(kept.visible, false);
memory.set("ash:inspector:task:root", JSON.stringify({ activeTab: "files", visible: true }));
rememberFamilyInspector("root", "leaf", all);
assert.deepEqual(takeInspectorEntry("leaf"), { id: "files", visible: true });
rememberFamilyInspector("root", "unrelated", [...all, task("unrelated")]);
assert.equal(takeInspectorEntry("unrelated"), undefined);
assert.equal(dispatchedWord({ ...run, status: "queued", queueId: "q", queuePosition: 3 }).word, "排第 4");
assert.equal(dispatchedMeta(leaf, now), "选哪个？");
assert.equal(dispatchedMeta(accepted, now), "");
assert.equal(dispatchedMeta(canceled, now), "");
assert.equal(dispatchedOrder([run, mid]), "同时");
assert.equal(dispatchedOrder([{ ...run, queueId: "q" }, { ...mid, queueId: "q" }]), "一个接一个");
assert.equal(dispatchedOrder([{ ...run, queueId: "q" }, mid]), null);
assert.equal(dispatchSubtree(family.children, "root").some((item) => item.id === "worker"), false);
console.log("✓ 子任务：侧栏收纳、筛选、全家表、逐层验收、导航与面板策略");
