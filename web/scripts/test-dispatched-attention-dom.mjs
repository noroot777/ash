import assert from "node:assert/strict";
import { launchChrome, startWebServer } from "./dom-stage.mjs";
import { WAIT_TIMEOUT_MS } from "./wait-until.mjs";

const web = await startWebServer();
let browser;
try {
  browser = await launchChrome();
  const page = await browser.newPage();
  page.setDefaultTimeout(WAIT_TIMEOUT_MS);
  const failures = [];
  page.on("pageerror", (error) => failures.push(error.message));
  await page.goto(`${web.origin}/scripts/fixtures/dispatched-attention.html`);
  const pane = (id) => page.locator(`[data-pane="${id}"]`);
  const row = (id) => page.locator(`[data-subtask-id="${id}"]`);
  const side = page.locator('[data-task-id="lead"]');
  const ask = (id) => row(id).locator(".dispatched-row__title");
  await pane("lead").waitFor();
  await row("kid-b").waitFor();
  assert.equal(await pane("lead").locator(".question-card").count(), 0);
  assert.equal(await side.locator(".workspace-dispatch-count").textContent(), "3");
  assert.equal(await side.locator(".dispatch-glyph.is-ask").count(), 1, "名下在问你：图标琥珀，数字不变色");
  assert.doesNotMatch(await side.innerText(), /子项/);
  assert.equal(await row("kid-b").locator("em").innerText(), "等你答复");
  assert.match(await row("kid-b").locator("small").innerText(), /第二条的问题/);
  await pane("lead").getByRole("textbox", { name: "回复任务" }).fill("先汇总父任务的进度");
  await pane("lead").getByRole("textbox", { name: "回复任务" }).press("Enter");
  await page.waitForFunction(() => window.__server.requests().some((request) => request.url === "/tasks/lead/reply"));
  assert.deepEqual(await page.evaluate(() => window.__server.requests().map((item) => item.url)), ["/tasks/lead/reply"]);
  await ask("kid-b").click();
  await pane("kid-b").locator(".question-card").waitFor();
  assert.equal(await page.locator("aside.side-drawer").count(), 0);
  assert.equal(await side.getAttribute("aria-selected"), "true");
  assert.equal(await page.locator("[data-subtask-id]").count(), 0, "子任务页不沿用父任务的表");
  await pane("kid-b").getByRole("button", { name: "要", exact: true }).click();
  await pane("kid-b").getByRole("button", { name: "发送答复" }).click();
  await page.waitForFunction(() => window.__server.requests().some((request) => request.url === "/tasks/kid-b/answer"));
  assert.equal(await page.evaluate(() => window.__server.requests().find((item) => item.url === "/tasks/kid-b/answer").body.via), undefined);
  await page.getByRole("button", { name: "父任务：拆活的分析任务", exact: true }).click();
  await ask("kid-a").click();
  await pane("kid-a").getByRole("button", { name: "先迁数据", exact: true }).click();
  await pane("kid-a").getByRole("button", { name: "发送答复" }).click();
  await page.waitForFunction(() => !document.querySelector('[data-task-id="lead"] .dispatch-glyph:is(.is-ask, .is-bad)'));
  await page.evaluate(() => window.__server.fail("kid-c"));
  await page.waitForFunction(() => document.querySelector('[data-task-id="lead"] .dispatch-glyph.is-bad'));
  await side.click();
  assert.equal(await row("kid-c").locator("em.is-bad").textContent(), "失败");
  assert.doesNotMatch(await side.innerText(), /子项/);
  assert.equal(await page.locator(".workspace-task-row-wrap", { has: side }).locator(".workspace-status-dot--bad").count(), 0, "名下摔了只写在行尾，圆点照旧说它自己");
  await page.evaluate(() => {
    window.__server.add({ id: "mid", title: "再往下一层", dispatchedBy: "kid-b", status: "done" });
    window.__server.add({ id: "grand", title: "孙一层", dispatchedBy: "mid", status: "paused", question: "孙一层的问题？" });
  });
  await row("grand").waitFor();
  assert.equal(await row("kid-b").locator(".dispatched-fold .dispatch-glyph.is-ask").count(), 1, "右侧那一行的折叠键：名下在问你，图标琥珀");
  await ask("grand").click();
  await pane("grand").locator(".question-card").waitFor();
  await page.reload();
  await pane("grand").locator(".question-card").waitFor();
  assert.equal(await side.getAttribute("aria-selected"), "true");
  assert.equal(await page.locator("[data-subtask-id]").count(), 0, "孙任务刷新后仍是自己的空表");
  await page.evaluate(() => {
    window.__server.patch("kid-b", { archived: true });
    window.__server.patch("mid", { archived: true });
  });
  assert.equal(await page.locator("[data-subtask-id]").count(), 0);
  assert.equal(await row("mid").count(), 0);
  assert.equal(await page.locator('[data-task-id="grand"]').count(), 0);
  assert.deepEqual(failures, []);
  console.log("✓ 子任务问题只在自己的完整页答复，祖先汇总一致，多层与刷新不丢选中");
} finally { await browser?.close(); await web.close(); }
