// 「没有发现问题」那条岔路——**报告自相矛盾时怎么办**。问题条目本身怎么证明在
// `test-review-report-problem-proof.mjs`，那一份的头上列着完整的判据谱系。
//
// 拆出来是因为那份写到 737 行（上限 700），而这一支自成一件事：它要判的不是「问题写全了
// 没有」，是**报告自己两句话对不对得上**。契约允许一份报告在问题栏只写「没有发现问题」
// 六个字，可这句话只有在报告别处没有反着说时才算数。三轮下来被抓到四种反着说的写法：
//
// ① 「这一栏有没有哪一行**包含**『没有发现问题』」证明不了没问题：「详情见下方；这里不是
//    说没有发现问题」这句否定句把判据整个翻了过来（第 4 轮）。所以改成**整栏比对**——问的
//    不是「出现过吗」，是「除了它还写了别的吗」。
// ② 同一份报告一边写「不能 —— 有 2 条必须先修」、一边写「没有发现问题」（第 8 轮）：零条目
//    那一支曾经直接返回，把条数校验整个跳过去。报了数就得对得上。
// ③ 条数只是矛盾的一种写法（复审第 1 轮）：`不能验收，请修完再验` 一个数字都不报，② 那道
//    闸读不到数就照放。所以第一栏得**读得出一句明确的正面判定**。反方向同理——第一栏写着
//    「可以验收」、明细里却躺着一条写全三行的问题，那也是矛盾。
// ④ 「正面判定」按**整段搜子串**问又松了一档（复审第 2 轮）：「不建议通过」「暂缓通过」
//    「not verified」「测试通过，但暂不验收」，四句话都是不能验收，整段里却都有正面词。
//    改成按判定本身读——主句里不许有否定修饰、得有肯定判定词，整段再扫一遍「主句说能、
//    后半句反悔」。同轮还有个差一个等号的边界：那条问题**自己就是第二个 `##`** 时，扫后文
//    的范围把它排除在外了。
//
// 每次都是同一个形状：判据比它要证明的事松一档，于是首屏写着一句话、折叠里躺着相反的
// 事实，而按钮还在宣称「里面只有验证过程、证据、清场记录」。拿不准一律降档。
import assert from "node:assert/strict";
import { splitReviewReport } from "../src/components/reviewReportSections.ts";

// 别矫枉过正：没问题那一支照拆。契约给的固定文案就是「没有发现问题」六个字。
for (const [kind, column] of [
  ["单起一段", "**必须修的问题**\n\n没有发现问题"],
  ["写在同一行", "**必须修的问题**：没有发现问题"],
]) {
  const clean = [
    "# 报告",
    "",
    "## 结论",
    "",
    "**能不能验收**：可以",
    "",
    "**现在什么能用了**：烧录前会先等字幕落盘。",
    "",
    column,
    "",
    "**不拦验收、但你该知道的**：没有。",
    "",
    "## 明细",
    "",
    "略",
  ].join("\n");
  assert.match(splitReviewReport(clean).detail, /^## 明细/, `${kind}：没问题的报告照样要拆`);
}

// 「没有发现问题」这一栏也得**对得上条数**。第 8 轮的反例：同一份报告一边写「不能 ——
// 有 2 条必须先修」，一边在问题栏写「没有发现问题」，两条真问题在下一个 `##` 里。零条目
// 那一支曾经直接返回、把条数校验整个跳过去，于是首屏同时显示这两句自相矛盾的话，按钮
// 还宣称折叠里只有验证记录。报告自相矛盾时不许挑对自己有利的那一半读。
{
  const contradictory = [
    "## 结论",
    "",
    "**能不能验收**：不能 —— 有 2 条必须先修。",
    "",
    "**现在什么能用了**：页面可以打开。",
    "",
    "**必须修的问题**：",
    "",
    "没有发现问题",
    "",
    "**不拦验收、但你该知道的**：没有。",
    "",
    "## 技术明细",
    "",
    "### 保存后内容消失",
    "你会遇到：保存后刚写的内容消失。",
    "为什么：保存请求没有落盘。",
    "建议怎么修：修复保存流程。",
  ].join("\n");
  const { summary, detail, kind } = splitReviewReport(contradictory);
  assert.equal(kind, "whole", "说了有 2 条又说没有发现问题，证明不了任何事");
  assert.equal(detail, "");
  assert.match(summary, /保存后内容消失/, "真问题必须留在首屏");
}

// 别把上面那条读成「没问题的报告也得报数」：没报数、或者明写「有 0 条」，都跟「没有发现
// 问题」一致，照拆。
for (const [what, verdict] of [
  ["没报数", "可以"],
  ["明写 0 条", "可以 —— 有 0 条必须先修"],
]) {
  const clean = [
    "## 结论",
    "",
    `**能不能验收**：${verdict}`,
    "",
    "**现在什么能用了**：烧录前会先等字幕落盘。",
    "",
    "**必须修的问题**：没有发现问题",
    "",
    "**不拦验收、但你该知道的**：没有。",
    "",
    "## 明细",
    "",
    "略",
  ].join("\n");
  assert.equal(splitReviewReport(clean).kind, "contract", `${what}：跟「没有发现问题」不矛盾`);
}

// 「对数」只是矛盾的一种写法。复审第 1 轮的反例换个写法就绕过去了：第一栏写「不能验收，
// 请修完再验」，一个数字都不报，② 那道闸读不到数于是照放——首屏同时写着「不能验收」和
// 「没有发现问题」，真问题在下一个 `##` 里，按钮还在替它背书。所以第一栏得**读得出一个
// 明确的正面判定**才算数，读不出（含糊、否定、干脆没写）一律降档。
{
  const contradicts = (verdict, detail) => [
    "## 结论",
    "",
    `**能不能验收**：${verdict}`,
    "",
    "**现在什么能用了**：页面可以打开。",
    "",
    "**必须修的问题**：",
    "",
    "没有发现问题",
    "",
    "**不拦验收、但你该知道的**：没有。",
    "",
    "## 技术明细",
    "",
    ...detail,
  ].join("\n");
  const realProblem = [
    "### 保存后内容消失",
    "你会遇到：保存后刚写的内容消失。",
    "为什么：保存请求没有落盘。",
    "建议怎么修：修复保存流程。",
  ];

  for (const [what, verdict] of [
    ["不报数的否定", "不能验收，请修完再验"],
    ["明写 0 条的否定", "不能 —— 有 0 条必须先修"],
    ["压根没写判定", "见下方说明"],
    ["未通过", "未通过，等修复后重验"],
  ]) {
    const { summary, detail, kind } = splitReviewReport(contradicts(verdict, realProblem));
    assert.equal(kind, "whole", `${what}：第一栏读不出正面判定，证明不了任何事`);
    assert.equal(detail, "");
    assert.match(summary, /保存后内容消失/, `${what}：真问题必须留在首屏`);

    // **同一份报告，明细里换成纯技术记录。**上面那条其实是两道闸一起拦的（明细里那条
    // 完整问题自己就够降档），把它拿掉才验得出第一栏这道闸单独管不管用——没有它，这份
    // 「说不能验收、又说没有发现问题」的报告会照判契约。
    //
    // 明细里确实没有契约格式的问题时也得降档，不是较真：问题多半是被写成散文了，而
    // `hidesProblem` 只认那固定三行，认不出散文形态。第一栏这道闸挡的正是它认不出的那一半。
    assert.equal(
      splitReviewReport(contradicts(verdict, ["构建与测试均退出 0。"])).kind,
      "whole",
      `${what}：明细里看不出问题也照样降档——两句话对不上就是对不上`,
    );
  }

  // 反方向的同一件事：第一栏写着能验收、问题栏写着没有发现问题，明细里却躺着一条写全
  // 三行的问题。按钮同样会替它宣称「里面只有验证过程、证据、清场记录」。
  for (const verdict of ["可以验收", "能 —— 全部通过", "verified"]) {
    const { summary, kind } = splitReviewReport(contradicts(verdict, realProblem));
    assert.equal(kind, "whole", `${verdict}：说没问题却把一条完整问题写在明细里，也是矛盾`);
    assert.match(summary, /保存后内容消失/, "那一条得留在首屏");
  }

  // 别把上面那条读成「明细里不许出现那三个词」。判据跟摘要里认问题用的是同一把尺——按序、
  // 各自独占行首、冒号后有字、而且得是正文。下面四种都**不是**一条问题，照样走契约档：
  for (const [what, detail] of [
    ["只提了其中一行", ["### 验证方式", "你会遇到：本轮没有可复现的问题。"]],
    ["三行顺序反了", ["### 验证方式", "建议怎么修：无。", "为什么：无。", "你会遇到：无。"]],
    ["写在围栏里的模板", ["### 写法示例", "```md", "你会遇到：…", "为什么：…", "建议怎么修：…", "```"]],
    ["冒号后空着", ["### 模板", "你会遇到：", "为什么：", "建议怎么修："]],
  ]) {
    assert.equal(
      splitReviewReport(contradicts("可以验收", detail)).kind,
      "contract",
      `${what}：够不上一条问题，不该把合规报告降档`,
    );
  }

  // 正样本兜底：真·没问题的报告一个字都没变，照拆。
  assert.equal(
    splitReviewReport(contradicts("可以 —— 有 0 条必须先修", ["构建与测试均退出 0。"])).kind,
    "contract",
    "没问题就是没问题，别把这一档一起收掉",
  );

  // 复审第 2 轮 · 其一：那条问题**自己就是第二个 `##`**。扫后文问题时写的是
  // `at <= tail`，而 `tail` 正是第二个 `##` 的行号——差这一个等号，问题标题就落在
  // 检查范围外，报告照判契约、问题照样进折叠。
  {
    const atBoundary = [
      "## 结论",
      "",
      "**能不能验收**：可以验收。",
      "",
      "**现在什么能用了**：页面能打开。",
      "",
      "**必须修的问题**：",
      "",
      "没有发现问题",
      "",
      "**不拦验收、但你该知道的**：没有。",
      "",
      "## 保存后内容消失",
      "你会遇到：保存后刚写的内容消失。",
      "为什么：保存请求没有落盘。",
      "建议怎么修：修复保存流程。",
    ].join("\n");
    const { summary, detail, kind } = splitReviewReport(atBoundary);
    assert.equal(kind, "whole", "分界标题本身就是那条问题时，同样不许判契约");
    assert.equal(detail, "");
    assert.match(summary, /保存后内容消失/, "它必须留在首屏");

    // 边界另一侧：摘要里的条目在 `tail` 之前，不该因为放宽边界被重复算成「明细里的问题」。
    assert.equal(
      splitReviewReport([
        "## 结论",
        "",
        "**能不能验收**：不能 —— 有 1 条必须先修。",
        "",
        "**现在什么能用了**：页面能打开。",
        "",
        "**必须修的问题**：",
        "",
        "### 保存后内容消失",
        "你会遇到：保存后刚写的内容消失。",
        "为什么：保存请求没有落盘。",
        "建议怎么修：修复保存流程。",
        "",
        "**不拦验收、但你该知道的**：没有。",
        "",
        "## 技术明细",
        "",
        "构建与测试均退出 0。",
      ].join("\n")).kind,
      "contract",
      "摘要里逐条写全的报告不受影响——它根本不走零条目那一支",
    );
  }

  // 复审第 2 轮 · 其二：第一栏的判定按**整段搜子串**问，太松。这四句话的意思都是
  // 「不能验收」，可整段里都躺着一个正面词（「通过」「verified」），于是照判契约。
  // 明细里那行风险说明**没按固定三行写**，所以第三道闸看不出异常——全靠第一栏这道。
  for (const verdict of [
    "不建议通过，修完再验",
    "暂缓通过，等人工确认",
    "not verified; fix before acceptance",
    "测试通过，但暂不验收",
    "可能可以验收，等人工再看一眼",
  ]) {
    assert.equal(
      splitReviewReport(contradicts(verdict, ["改名只写了内存那份、刷新就回退，这一条还没修。"])).kind,
      "whole",
      `「${verdict}」不是一句「能验收」，别让正面子串替它作证`,
    );
  }

  // 反过来也得验：真实语料里走这条岔路的 6 份报告，主句就是下面这三种写法，一份都不能误伤。
  for (const verdict of ["可以验收。", "能验收。", "可以 —— 第 1 轮的 2 条都已修复，本轮没有发现必须先修的问题。"]) {
    assert.equal(
      splitReviewReport(contradicts(verdict, ["构建与测试均退出 0。"])).kind,
      "contract",
      `「${verdict}」是一句明确的正面判定，照拆`,
    );
  }
}

// 「没有发现问题」这一栏得**整栏只写这六个字**，不是「哪一行里出现过」。第 4 轮的反例：
// 问题栏写着「详情见下方；这里不是说没有发现问题」，一句否定句就把判据翻了过来——真正的
// 问题写在后面的 `##` 里，首屏只剩「有 1 条必须先修」和「详情见下方」，按钮还宣称折叠里
// 是「验证过程、证据、清场记录」。引文、注释、代码示例里出现同样字样是同一个洞。
for (const [what, column] of [
  ["否定句", "详情见下方；这里不是说没有发现问题"],
  ["带条件", "没有发现问题，但建议后续再看一眼导出路径"],
  ["引文里提过", "> 上一轮写的是「没有发现问题」\n\n本轮的问题见下方。"],
  ["代码示例里提过", "```text\n没有发现问题\n```"],
  ["整栏空着", ""],
]) {
  const evasive = [
    "# 报告",
    "",
    "## 结论",
    "",
    "**能不能验收**：不能 —— 有 1 条必须先修",
    "",
    "**现在什么能用了**：基础流程可用。",
    "",
    "**必须修的问题**",
    "",
    column,
    "",
    "**不拦验收、但你该知道的**：没有。",
    "",
    "## 保存后内容会全部消失",
    "",
    "你会遇到：点保存以后整篇内容清空。",
  ].join("\n");
  const { summary, detail, kind } = splitReviewReport(evasive);
  assert.equal(kind, "whole", `${what}：不是「只写了那六个字」，证明不了问题在摘要里`);
  assert.equal(detail, "");
  assert.match(summary, /保存后内容会全部消失/, `${what}：问题必须留在首屏`);
}

// 容一个句号，别的都不容——这是「整栏比对」留的唯一余地。
{
  const period = [
    "# 报告",
    "",
    "## 结论",
    "",
    "**能不能验收**：可以",
    "",
    "**现在什么能用了**：略",
    "",
    "**必须修的问题**",
    "",
    "没有发现问题。",
    "",
    "**不拦验收、但你该知道的**：没有。",
    "",
    "## 明细",
    "",
    "略",
  ].join("\n");
  assert.equal(splitReviewReport(period).kind, "contract", "结尾那个句号不算「多写了东西」");
}

