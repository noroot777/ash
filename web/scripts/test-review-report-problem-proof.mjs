// 四栏齐了之后**怎么证明问题真的在摘要里**——签名判据的第二道闸。第一道闸（四栏齐全、
// 按序、不重样、写在够格的位置上）在 `test-review-report-sections.mjs`，四栏写成 `###`
// 小标题那一档在 `test-review-report-heading-columns.mjs`。
//
// 拆出来是因为那份文件又写到 682 行（上限 700）。这一档自成一件事，而且两种栏目写法共用
// 同一套判据：光有四个标签不算数，第二个 `##` 之后是不是技术记录得由报告自己证明。判据
// 照契约本身来（`server/src/review-report-format.ts`）——要么每条问题一个小标题**并带着
// 「你会遇到 / 为什么 / 建议怎么修」那固定三行**，要么这一栏**只写**「没有发现问题」。
//
// 八条别再走回头路的判据，都是同一种形状——**判据比它要证明的事松一档**：
// ① 「有没有一个够深的标题」证明不了有问题：`#### 补充说明` + 「真正的问题见下方」就能
//    冒充问题条目（第 5 轮）。得验那三行，而且按序、各自独占一行的开头。
// ② 别把 ① 的三行退回子串问法：「这里不写你会遇到、为什么、建议怎么修」一句话就够。
// ③ 「**有一条**写对了」证明不了「问题都在摘要里」（第 6 轮）：栏里每个小标题都得是一条
//    按契约写的问题——契约原话「扫标题要能数清楚一共几条」，混个说明性标题就数不清了。
// ④ 逐条验完还是不够：少的那条可能**根本不在这一栏里**。「能不能验收」报了「有 2 条」、
//    摘要里只写了 1 条时，第二条正躺在折叠里（第 6 轮）。报了数就得对得上。
// ⑤ 那三行得是**正文**、冒号后得**真有字**：围栏里的写法示例和只留冒号的空占位都能凑齐
//    三行（第 6 轮）。节点类型走跟栏目检测同一套白名单，黑名单永远缺一条。「真有字」问的
//    还得是**渲染结果**——`你会遇到：[](#symptom)` 源码里有字符、页面上一个字都没有
//    （复审第 7 轮）。「渲染结果」里**不含图片的 `alt`**：图片出来是一张图，`alt` 只在点开
//    灯箱后当标题出现，本地磁盘路径的图 `MarkdownBody` 干脆不渲染（复审第 8 轮）。
// ⑥ 「**没报数就不管**」等于把 ④ 让开一条道（第 7 轮）：不写数字、第二条写成下一个 `##`，
//    逐条验的是摘要里那条合规的，照样判成契约。数不出总数就证明不了摘要是全的——契约本来
//    就要求「不能的话写『有 N 条必须先修』」，所以这不是提新要求，是不再替它补全。中文
//    数字（「有两条」）也得认，否则报了数跟没报数一个待遇。
// ⑦ 「其余 N 条」那条分流行得**真是那一行**（第 7 轮）：只在问题栏开头 64 行里搜关键词时，
//    第一条问题的现象写成「页面只显示其余 3 条记录」就够了。位置（第 5 条之后的独立顶层
//    段落）、数目（`N = 总数 - 5`），一件都不能省。
// ⑧ 前七条都在收紧「怎么证明」，第 8 轮那条「其余 3 条：详见明细」说明有一件事**证明不
//    了**：明细里到底有没有那几条。契约允许它们写在任何一节里，冒号后有没有字跟这件事
//    没关系。所以换了个方向——**这一档根本不发那句承诺**：写了分流行的报告降到 `lead`，
//    5 条问题和分流声明全留在首屏，按钮换成什么都不宣称的「展开完整报告」。判据管不住
//    报告说什么，只管得住自己说什么。
//
// 另一条岔路——问题栏只写「没有发现问题」时**报告自己两句话对不对得上**——在
// `test-review-report-contradiction.mjs`：那一支被抓到过四种「反着说」的写法，判据谱系
// 写在它自己的头上。
//
// 每次都是同一个后果：首屏写着有问题，问题本身进了那个宣称「里面只有验证过程、证据、
// 清场记录」的折叠。拿不准一律降档——多点一下按钮，比按钮替报告撒谎便宜得多。
import assert from "node:assert/strict";
