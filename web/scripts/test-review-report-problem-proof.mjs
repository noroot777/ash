// 四栏齐了之后**怎么证明问题真的在摘要里**——签名判据的第二道闸。第一道闸（四栏齐全、
// 按序、不重样、写在够格的位置上）在 `test-review-report-sections.mjs`，四栏写成 `###`
// 小标题那一档在 `test-review-report-heading-columns.mjs`。
//
// 拆出来是因为那份文件又写到 682 行（上限 700）。这一档自成一件事，而且两种栏目写法共用
// 同一套判据：光有四个标签不算数，第二个 `##` 之后是不是技术记录得由报告自己证明。判据
// 照契约本身来（`server/src/review-report-format.ts`）——要么每条问题一个小标题**并带着
// 「你会遇到 / 为什么 / 建议怎么修」那固定三行**，要么这一栏**只写**「没有发现问题」。
//
// 三条别再走回头路的判据，都是同一种形状——**判据比它要证明的事松一档**：
// ① 「有没有一个够深的标题」证明不了有问题：`#### 补充说明` + 「真正的问题见下方」就能
//    冒充问题条目（第 5 轮）。得验那三行，而且按序、各自独占一行的开头。
// ② 「这一栏有没有哪一行**包含**『没有发现问题』」证明不了没问题：「这里不是说没有发现
//    问题」这句否定句把判据整个翻了过来（第 4 轮）。得整栏比对。
// ③ 别把 ① 的三行也退回子串问法：「这里不写你会遇到、为什么、建议怎么修」一句话就够。
//
// 三次都是同一个后果：首屏写着有问题，问题本身进了那个宣称「里面只有验证过程、证据、
// 清场记录」的折叠。拿不准一律降到第二档——多点一下按钮，比按钮替报告撒谎便宜得多。
import assert from "node:assert/strict";
import { splitReviewReport } from "../src/components/reviewReportSections.ts";

// 四个标签齐了还不够——得**证明问题本身就在摘要里**。第 10 轮的反例：摘要写着「不能 ——
// 有 1 条必须先修」「必须修的问题：见下方」，那一条却写成了下一个 `##`，于是首屏只剩
// 「见下方」，问题在折叠里。判据照契约本身来：要么每条问题一个小标题，要么只写「没有
// 发现问题」。
{
  const misplaced = [
    "# 报告",
    "",
    "## 结论",
    "",
    "**能不能验收**：不能 —— 有 1 条必须先修",
    "",
    "**现在什么能用了**：略",
    "",
    "**必须修的问题**：见下方",
    "",
    "**不拦验收、但你该知道的**：没有",
    "",
    "## 保存后你刚改的内容会全部消失",
    "",
    "你会遇到：点保存回到列表，刚写的东西没了。",
  ].join("\n");
  const { summary, detail } = splitReviewReport(misplaced);
  assert.equal(detail, "", "拿不出小标题也拿不出「没有发现问题」，就不能拆");
  assert.match(summary, /保存后你刚改的内容会全部消失/, "问题必须留在首屏");
}

// 别矫枉过正：没问题那一支照拆。契约给的固定文案就是「没有发现问题」六个字。
for (const [kind, column] of [
  ["单起一段", "**必须修的问题**\n\n没有发现问题"],
  ["写在同一行", "**必须修的问题**：没有发现问题"],
]) {
  const clean = [
    "# 报告",
    "",
    "## 结论",
    "",
    "**能不能验收**：可以",
    "",
    "**现在什么能用了**：烧录前会先等字幕落盘。",
    "",
    column,
    "",
    "**不拦验收、但你该知道的**：没有。",
    "",
    "## 明细",
    "",
    "略",
  ].join("\n");
  assert.match(splitReviewReport(clean).detail, /^## 明细/, `${kind}：没问题的报告照样要拆`);
}

// 但「没有发现问题」这一栏得**整栏只写这六个字**，不是「哪一行里出现过」。第 4 轮的反例：
// 问题栏写着「详情见下方；这里不是说没有发现问题」，一句否定句就把判据翻了过来——真正的
// 问题写在后面的 `##` 里，首屏只剩「有 1 条必须先修」和「详情见下方」，按钮还宣称折叠里
// 是「验证过程、证据、清场记录」。引文、注释、代码示例里出现同样字样是同一个洞。
for (const [what, column] of [
  ["否定句", "详情见下方；这里不是说没有发现问题"],
  ["带条件", "没有发现问题，但建议后续再看一眼导出路径"],
  ["引文里提过", "> 上一轮写的是「没有发现问题」\n\n本轮的问题见下方。"],
  ["代码示例里提过", "```text\n没有发现问题\n```"],
  ["整栏空着", ""],
]) {
  const evasive = [
    "# 报告",
    "",
    "## 结论",
    "",
    "**能不能验收**：不能 —— 有 1 条必须先修",
    "",
    "**现在什么能用了**：基础流程可用。",
    "",
    "**必须修的问题**",
    "",
    column,
    "",
    "**不拦验收、但你该知道的**：没有。",
    "",
    "## 保存后内容会全部消失",
    "",
    "你会遇到：点保存以后整篇内容清空。",
  ].join("\n");
  const { summary, detail, kind } = splitReviewReport(evasive);
  assert.equal(kind, "whole", `${what}：不是「只写了那六个字」，证明不了问题在摘要里`);
  assert.equal(detail, "");
  assert.match(summary, /保存后内容会全部消失/, `${what}：问题必须留在首屏`);
}

// 容一个句号，别的都不容——这是「整栏比对」留的唯一余地。
{
  const period = [
    "# 报告",
    "",
    "## 结论",
    "",
    "**能不能验收**：可以",
    "",
    "**现在什么能用了**：略",
    "",
    "**必须修的问题**",
    "",
    "没有发现问题。",
    "",
    "**不拦验收、但你该知道的**：没有。",
    "",
    "## 明细",
    "",
    "略",
  ].join("\n");
  assert.equal(splitReviewReport(period).kind, "contract", "结尾那个句号不算「多写了东西」");
}

// 问题小标题也得**真是一条问题**，不是随便一个够深的标题。第 5 轮的反例：问题栏底下写
// 个 `### 补充说明` + 「真正的问题见下方。」，判据只数「有没有一个够深的标题」时照样判成
// 契约，那一条真正的问题写在后面的 `##` 里，按钮还宣称折叠里只有技术记录。判据照契约验
// 那三行（`server/src/review-report-format.ts`：「每条一个小标题，固定三行」）。
for (const [what, item] of [
  ["说明性标题", "### 补充说明\n\n真正的问题见下方。"],
  ["只写了第一行", "### 1. 导出内容仍是旧版本\n\n你会遇到：导出的还是上一版。"],
  ["缺「建议怎么修」", "### 1. 导出内容仍是旧版本\n\n你会遇到：导出的还是上一版。\n为什么：读的是缓存。"],
  ["三行顺序乱了", "### 1. 导出内容仍是旧版本\n\n建议怎么修：先对齐缓存。\n为什么：读的是缓存。\n你会遇到：导出的还是上一版。"],
  ["只是句子里提了一嘴", "### 补充说明\n\n这里不写你会遇到、为什么、建议怎么修，真正的问题见下方。"],
]) {
  const faked = [
    "# 报告",
    "",
    "## 结论",
    "",
    "**能不能验收**：不能 —— 有 1 条必须先修",
    "",
    "**现在什么能用了**：基础流程可以正常打开。",
    "",
    "**必须修的问题**",
    "",
    item,
    "",
    "**不拦验收、但你该知道的**：没有。",
    "",
    "## 保存后内容会全部消失",
    "",
    "你会遇到：点保存回到列表，刚写的内容没了。",
  ].join("\n");
  const { summary, detail, kind } = splitReviewReport(faked);
  assert.equal(kind, "whole", `${what}：小标题底下没有一条按契约写的问题`);
  assert.equal(detail, "");
  assert.match(summary, /保存后内容会全部消失/, `${what}：问题必须留在首屏`);
}

// 三行的写法照栏目标签的尺度容：加粗写不写、冒号在加粗里还是外面、前面带不带列表符号。
for (const [what, lines] of [
  ["光秃秃三行", "你会遇到：导出的还是上一版。\n为什么：读的是缓存。\n建议怎么修：先对齐缓存。"],
  ["加粗标签", "**你会遇到**：导出的还是上一版。\n**为什么**：读的是缓存。\n**建议怎么修**：先对齐缓存。"],
  ["冒号在加粗里", "**你会遇到：**导出的还是上一版。\n**为什么：**读的是缓存。\n**建议怎么修：**先对齐缓存。"],
  ["列表符号打头", "- 你会遇到：导出的还是上一版。\n- 为什么：读的是缓存。\n- 建议怎么修：先对齐缓存。"],
  ["中间夹着别的话", "你会遇到：导出的还是上一版。\n\n（本轮复现 3 次）\n\n为什么：读的是缓存。\n\n建议怎么修：先对齐缓存。"],
]) {
  const real = [
    "# 报告",
    "",
    "## 结论",
    "",
    "**能不能验收**：不能 —— 有 1 条必须先修",
    "",
    "**现在什么能用了**：略",
    "",
    "**必须修的问题**",
    "",
    "### 1. 导出内容仍是旧版本",
    "",
    lines,
    "",
    "**不拦验收、但你该知道的**：没有。",
    "",
    "## 明细",
    "",
    "略",
  ].join("\n");
  assert.equal(splitReviewReport(real).kind, "contract", `${what}：这是一条按契约写的问题`);
}

