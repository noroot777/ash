// 契约允许**摘要里最多展开 5 条**，更多的在第 5 条后面写一行「其余 N 条：<标题>、<标题>……
// 完整写在下面的技术明细里」，完整三行放进明细。这种报告**格式完全合规，但折叠里确实有
// 问题**——第 6 条往后就躺在里面。所以它不走契约档：照样从第二个 `##` 起折（5 条问题和
// 那行分流声明全留在首屏），按钮换成什么都不宣称的「展开完整报告」。
//
// 第 8 轮的反例是这条的直接后果：「其余 3 条：详见明细」而明细里一条都没有。拿「冒号后
// 有没有字」去证明「明细里真有那三条」永远证明不到——契约允许它们写在任何一节里。解析器
// 管得住的只有自己那句承诺，所以这一档根本不发那句承诺。
const five = Array.from({ length: 5 }, (_, k) => [
  `### ${k + 1}. 导出内容仍是旧版本（${k + 1}）`,
  "",
  "你会遇到：导出的还是上一版。",
  "为什么：读的是缓存。",
  "建议怎么修：先对齐缓存。",
  "",
].join("\n")).join("");
const capped = (declared, spill) =>
  `# 报告\n\n## 结论\n\n**能不能验收**：不能 —— 有 ${declared} 条必须先修\n\n`
  + `**现在什么能用了**：略\n\n**必须修的问题**\n\n${five}\n${spill}\n**不拦验收、但你该知道的**：没有。\n\n## 明细\n\n略\n`;
for (const [what, spill] of [
  ["列了标题", "其余 3 条：导入失败、预览错位、快捷键失灵……完整写在下面的技术明细里。\n"],
  ["只写详见明细", "其余 3 条：详见明细\n"],
]) {
  const { summary, detail, kind } = splitReviewReport(capped(8, spill));
  assert.equal(kind, "lead", `${what}：折叠里有第 6 条往后，按钮不准说里面只有技术记录`);
  assert.match(summary, /5\. 导出内容仍是旧版本（5）/, `${what}：5 条问题全留在首屏`);
  assert.match(summary, /其余 3 条/, `${what}：分流声明也留在首屏`);
  assert.match(detail, /^## 明细/, `${what}：拆点仍是第二个 ` + "`##`");
}

// 这条分流行得**真是那一行**。三种写法都曾经能混过去，后果一样：摘要只有 5 条，明细里
// 第 6～8 条根本不存在，按钮照样说折叠里只有验证记录。
for (const [what, declared, spill] of [
  // ① 数目不对：「有 8 条」配「其余 1 条」等于承认 5 + 1 = 8。
  ["其余数目对不上", 8, "其余 1 条：导入失败。完整写在下面的技术明细里。\n"],
  // ② 清单空着：契约要的是「列出标题」，冒号后面没字证明不了明细里有东西。
  ["清单空着", 8, "其余 3 条：\n"],
  // ③ 压根没写分流行。
  ["没写分流行", 8, ""],
]) {
  assert.equal(splitReviewReport(capped(declared, spill)).kind, "whole", `${what}：证明不了第 6 条起在明细里`);
}

// 位置也是判据：分流行得在**第 5 条之后**、而且是独立的顶层段落。第 7 轮的反例把它写进了
// **第一条问题的现象**里——「你会遇到：页面只显示其余 3 条记录」，一句大白话就凑齐了签名。
{
  const inProse = capped(8, "").replace(
    "### 1. 导出内容仍是旧版本（1）\n\n你会遇到：导出的还是上一版。",
    "### 1. 列表只显示一部分\n\n你会遇到：页面只显示其余 3 条：甲、乙、丙，别的都不见了。",
  );
  assert.equal(splitReviewReport(inProse).kind, "whole", "写在第一条现象里的不是分流行");
}

// 围栏、引用、嵌套列表里的同一行也不算——跟问题三行同一套白名单。
for (const [what, spill] of [
  ["围栏里", "```text\n其余 3 条：导入失败、预览错位、快捷键失灵。\n```\n"],
  ["块引用里", "> 其余 3 条：导入失败、预览错位、快捷键失灵。\n"],
  ["嵌套列表里", "- 上一轮抄来的：\n  - 其余 3 条：导入失败、预览错位、快捷键失灵。\n"],
]) {
  assert.equal(splitReviewReport(capped(8, spill)).kind, "whole", `${what}的分流行不算数`);
}

