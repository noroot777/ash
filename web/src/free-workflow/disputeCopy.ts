export type DisputeResolutionKind = keyof typeof RESOLUTIONS;

/**
 * 按钮为什么按「接下来干什么」命名，不按「谁对」命名（用户 2026-09-27 拍的板）。
 *
 * 上一版叫「维持意见并修复」和「采纳执行者说法」——那是裁判用语，回答的是谁赢；而用户
 * 真正要做的是下一步的指令。两者一旦分叉，界面就会问出一个没有正确答案的问题：辩论辩出
 * 「第 2 条成立，但按后来达成的新方案做」时，既不是「维持」原报告（报告要的是另一版），
 * 也不是「采纳执行者」（它说的是这条不成立），用户只能在两颗都不对的按钮里挑一颗。
 *
 * 「谁对」是**事实**，仍要留档——它写在确认框末尾、时间线和审查记录里，那才是它该待的
 * 地方。按钮是下命令用的，不是记分用的。
 */
export function resolutionConfirmText(kind: DisputeResolutionKind, round: number): string {
  return RESOLUTIONS[kind].confirm.replace("{round}", String(round));
}

/**
 * 卡片标题：**系统自己推出来的**一句人话，不依赖 agent 怎么写。
 *
 * 三种形态由两段理由在不在决定，是结构事实，所以这一句永远可靠（agent 的那一句摘要摆在
 * 它下面）。只提转出时标题不能还写「驳回了意见」——那会让用户以为执行者在说报告不对，
 * 而它说的恰恰是「报告是对的，只是不该在这儿修」。
 */
export function disputeHeadline(round: FreeReviewRound, dispute: FreeReviewDispute): string {
  const n = round.round;
  if (!dispute.reason) return `执行者认可第 ${n} 轮意见，但说该另开一个任务去改`;
  if (dispute.deferReason) return `执行者不认第 ${n} 轮的部分意见，另几条说该另开任务去改`;
  return `执行者不认第 ${n} 轮审查意见`;
}

/** 两段正文各自的折叠标题（点开才是那一墙技术依据）。 */
export const DISPUTE_PROSE_LABELS = {
  reason: "它凭什么说这几条不成立",
  defer: "它认可、但说该另开任务的那几条",
} as const;

/**
 * 卡片中间那句状态行：此刻**卡在哪**、下一步归谁。
 *
 * 辩完那一句要点出要点栏：辩论最常见的结论恰恰落在三档之间（「这条我认，但按刚才达成的
 * 方案做」），不说的话用户只会在两颗都不对的按钮之间挑一颗。
 */
export function disputeStatusLine(debate: FreeReviewDebate | null): string {
  if (debate?.status === "running") return "双方正在各自陈词。辩论只产生发言，不改代码，说完还是你拍板。";
  if (debate?.status === "finished") {
    return "双方都说完了。审查者最后那句只是它自己的立场，拍板的是你；"
      + "想让它照某一段说的办，点那段上的「用这段作要点」。";
  }
  if (debate?.status === "failed") return "上一场辩论中途断了（有一段没能发言）。可以重开一场，也可以直接拍板。";
  return "这一轮停在这儿了：没有照着改，也没有算通过 —— 等你选一个。";
}
